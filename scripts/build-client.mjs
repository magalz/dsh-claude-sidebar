/**
 * Build the browser half of dsh-claude-sidebar: concatenate client/shared.js and the
 * files under features/<feature>/client/ into the single classic script client.js the app
 * loads. No transpiler, no JSX, no bundler: each part is plain JavaScript placed inside
 * one module factory.
 *
 * The app loads the output through window.__ModuleLoader__.load({ id, factory })
 * (dsh-plan-note lib/client.js:1-3,589-627; dsh-client-modules README.md:43,77).
 * React comes from the browser module table through require('react'); no part may
 * require any other module. Every feature after the shared prelude runs in its own block,
 * so its declarations stay private instead of replacing another feature's; the five
 * Environment files share that one block.
 *
 * Usage:
 *   node scripts/build-client.mjs          write client.js
 *   node scripts/build-client.mjs --check  write nothing; exit 1 when client.js is stale
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const OUTPUT = join(ROOT, 'client.js')

/**
 * The client features, in the fixed order of docs/specs/feature-rows.md. A feature's
 * files are listed in concatenation order; the Environment files share one block.
 */
export const FEATURES = [
  { name: 'rail', files: ['rail.js'] },
  { name: 'jobs', files: ['jobs.js'] },
  { name: 'subagents', files: ['subagents.js'] },
  {
    name: 'environment',
    files: [
      'environment-base.js',
      'environment-context.js',
      'environment-connectors.js',
      'environment-settings.js',
      'environment.js',
    ],
  },
  { name: 'run', files: ['run.js'] },
  { name: 'git', files: ['git.js'] },
  { name: 'sizing', files: ['sizing.js'] },
  { name: 'browser', files: ['browser.js'] },
]

/** The shared prelude, then each feature's files in order; a group entry shares one block. */
export const PARTS = [
  'shared.js',
  ...FEATURES.map(feature => (feature.files.length === 1 ? feature.files[0] : feature.files)),
]

/** Each source path relative to the repository root, in the order the build reads them. */
const sourceOf = new Map([
  ['shared.js', 'client/shared.js'],
  ...FEATURES.flatMap(feature =>
    feature.files.map(name => [name, 'features/' + feature.name + '/client/' + name]),
  ),
])
export const SOURCES = [...sourceOf.values()]

/** What every generated client.js opens with: the provenance and the one loader call. */
const HEADER = [
  '/**',
  ' * Generated from client/shared.js and features/<feature>/client/ by scripts/build-client.mjs.',
  ' * Do not edit this file by hand: change a source part and run `node scripts/build-client.mjs`.',
  ' *',
  ' * Browser half of dsh-claude-sidebar: one classic factory script the app loads through',
  ' * window.__ModuleLoader__.load. The parts below run in order inside one factory and share',
  " * its declarations; every feature after the shared prelude runs in its own block, so its",
  " * declarations stay private instead of replacing another feature's. The five Environment",
  ' * files share one block. The footer gates mounts on the Host feature list.',
  ' */',
].join('\n')

/** What every generated client.js closes with: the inject union and the gated mounts. */
const FOOTER = [
  "    /* The plugin object the app consumes: every feature's inject, gated mounts. */",
  '    return {',
  '      inject: FEATURES.reduce((names, feature) => {',
  '        for (const name of feature.inject) if (!names.includes(name)) names.push(name)',
  '        return names',
  '      }, []),',
  '      apply(ctx) {',
  '        /* Cordis waits on a promise returned by apply: never return the gate. */',
  '        let disposed = false',
  '        const controller = typeof AbortController === "function" ? new AbortController() : null',
  '        ctx.effect(() => () => {',
  '          disposed = true',
  '          if (controller) controller.abort()',
  "        }, 'dsh-claude-sidebar feature gate')",
  '        let timer = null',
  '        const clearTimer = () => {',
  '          if (timer !== null) clearTimeout(timer)',
  '          timer = null',
  '        }',
  '        const activate = names => {',
  '          if (disposed) return',
  '          ACTIVE_FEATURES.clear()',
  '          for (const name of names) ACTIVE_FEATURES.add(name)',
  '          for (const feature of FEATURES) {',
  '            if (!ACTIVE_FEATURES.has(feature.name)) continue',
  '            try {',
  '              feature.mount(ctx)',
  '            } catch (error) {',
  `              console.warn('dsh-claude-sidebar: feature "' + feature.name + '" failed to mount', error)`,
  '            }',
  '          }',
  '        }',
  '        const options = { cache: "no-store", credentials: "same-origin" }',
  '        if (controller) {',
  '          options.signal = controller.signal',
  '          timer = setTimeout(() => controller.abort(), 10_000)',
  '        }',
  "        fetch(api('/dsh-claude-sidebar/features'), options)",
  '          .then(response => {',
  "            if (!response.ok) throw new Error('feature list: HTTP ' + response.status)",
  '            return response.json()',
  '          })',
  '          .then(body => {',
  "            if (body === null || typeof body !== 'object' || Array.isArray(body) || !Array.isArray(body.features)) {",
  "              throw new Error('feature list: malformed answer')",
  '            }',
  '            activate(body.features)',
  '          })',
  '          .catch(error => {',
  '            if (disposed) return',
  "            console.warn('dsh-claude-sidebar: feature list unavailable; no feature mounted', error)",
  '          })',
  '          .then(clearTimer, clearTimer)',
  '      },',
  '    }',
].join('\n')

/** Read one part, as UTF-8, from the folder its feature lives in. */
function readPartFile(name) {
  const source = sourceOf.get(name)
  if (source === undefined) throw new Error('build-client: unknown part "' + name + '"')
  return readFileSync(join(ROOT, source), 'utf8')
}

/**
 * Build the full text of client.js.
 * @param {(name: string) => string} [readPart] - returns one part's text; defaults to reading the source path.
 * @param {(string | string[])[]} [parts] - file names or groups in concatenation order; defaults to PARTS.
 * @returns {string} the generated browser half: "\n" line endings, one final newline.
 */
export function buildClient(readPart = readPartFile, parts = PARTS) {
  const chunks = [
    HEADER,
    'window.__ModuleLoader__.load({',
    "  id: 'dsh-claude-sidebar',",
    '  factory(require) {',
    "    'use strict'",
  ]
  for (const [index, entry] of parts.entries()) {
    const names = Array.isArray(entry) ? entry : [entry]
    for (const [fileIndex, name] of names.entries()) {
      const text = readPart(name)
      if (typeof text !== 'string') throw new TypeError('build-client: part "' + name + '" did not read as text')
      chunks.push('', '    // ' + (sourceOf.get(name) ?? 'src/client/' + name))
      // shared.js declares what every later part uses; each later entry gets a block so its
      // declarations stay private instead of replacing an earlier entry's. A group of files
      // shares that one block, and therefore one scope.
      if (index > 0 && fileIndex === 0) chunks.push('    {')
      chunks.push(text.replace(/\r\n?/gu, '\n').replace(/\n+$/u, ''))
      if (index > 0 && fileIndex === names.length - 1) chunks.push('    }')
    }
  }
  chunks.push('', FOOTER, '  },', '})')
  return chunks.join('\n') + '\n'
}

/** The current client.js text, or null when it does not exist yet. */
function readOutput() {
  try {
    return readFileSync(OUTPUT, 'utf8')
  } catch {
    return null
  }
}

const invokedDirectly = process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href

if (invokedDirectly) {
  const check = process.argv.slice(2).includes('--check')
  const output = buildClient()
  if (!check) {
    writeFileSync(OUTPUT, output)
  } else if (readOutput() !== output) {
    console.error('client.js is stale; run `node scripts/build-client.mjs`')
    process.exitCode = 1
  }
}
